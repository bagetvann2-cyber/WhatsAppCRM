export function findPreset(id: string): ProfilePreset | undefined {
  return PROFILE_PRESETS.find((preset) => preset.id === id);
}

/** Места, которые клиенту осталось заполнить: `[уточните: цена доставки]`. */
export const PLACEHOLDER_PATTERN = /\[уточните:[^\]]*\]/g;

export function findPlaceholders(...texts: string[]): string[] {
  return texts.flatMap((source) => source.match(PLACEHOLDER_PATTERN) ?? []);
}
